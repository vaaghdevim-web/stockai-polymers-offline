-- ================================================================
-- SVP StockAI - PostgreSQL Database Schema V2.4
-- Factory + ERP + Inventory + IoT integrated architecture
-- PostgreSQL 14+
-- ================================================================

BEGIN;

SET search_path TO public;

-- ================================================================
-- 1. ORGANIZATION & LOCATION
-- ================================================================

CREATE TABLE IF NOT EXISTS plant (
    plant_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_name    VARCHAR(150) NOT NULL,
    city          VARCHAR(100),
    state         VARCHAR(100),
    country       VARCHAR(100),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_plant_name UNIQUE (plant_name)
);

CREATE TABLE IF NOT EXISTS warehouse (
    warehouse_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id       BIGINT NOT NULL REFERENCES plant(plant_id),
    warehouse_name VARCHAR(150) NOT NULL,
    type           VARCHAR(20) NOT NULL CHECK (type IN ('Raw','FG','Both')),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_warehouse_plant_name UNIQUE (plant_id, warehouse_name)
);

CREATE TABLE IF NOT EXISTS location_rack (
    rack_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    rack_code    VARCHAR(50) NOT NULL,
    is_active    BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_rack_warehouse_code UNIQUE (warehouse_id, rack_code)
);

CREATE TABLE IF NOT EXISTS location_shelf (
    shelf_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rack_id    BIGINT NOT NULL REFERENCES location_rack(rack_id),
    shelf_code VARCHAR(50) NOT NULL,
    is_active  BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_shelf_rack_code UNIQUE (rack_id, shelf_code)
);

CREATE TABLE IF NOT EXISTS location_bin (
    bin_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shelf_id  BIGINT NOT NULL REFERENCES location_shelf(shelf_id),
    bin_code  VARCHAR(50) NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_bin_shelf_code UNIQUE (shelf_id, bin_code)
);

-- ================================================================
-- 2. MASTER DATA
-- ================================================================

CREATE TABLE IF NOT EXISTS material_category (
    category_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL,
    category_type VARCHAR(30) NOT NULL
        CHECK (category_type IN ('Raw','Additive','Packaging','Other')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_material_category_name UNIQUE (category_name)
);

CREATE TABLE IF NOT EXISTS unit_of_measure (
    uom_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uom_code VARCHAR(20) NOT NULL UNIQUE,
    uom_type VARCHAR(30) NOT NULL
        CHECK (uom_type IN ('Weight','Quantity','Length','Area','Other'))
);

CREATE TABLE IF NOT EXISTS raw_material (
    material_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id     BIGINT NOT NULL REFERENCES material_category(category_id),
    default_uom_id  BIGINT NOT NULL REFERENCES unit_of_measure(uom_id),
    material_name   VARCHAR(150) NOT NULL,
    material_code   VARCHAR(50) NOT NULL UNIQUE,
    standard_cost   NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (standard_cost >= 0),
    reorder_level   NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    safety_stock    NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (safety_stock >= 0),
    lead_time_days  INTEGER NOT NULL DEFAULT 0 CHECK (lead_time_days >= 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product_category (
    prod_cat_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(100) NOT NULL UNIQUE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS finished_product (
    product_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prod_cat_id     BIGINT NOT NULL REFERENCES product_category(prod_cat_id),
    default_uom_id  BIGINT NOT NULL REFERENCES unit_of_measure(uom_id),
    product_name    VARCHAR(150) NOT NULL,
    product_code    VARCHAR(50) NOT NULL UNIQUE,
    standard_cost   NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (standard_cost >= 0),
    selling_price   NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (selling_price >= 0),
    reorder_level   NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (reorder_level >= 0),
    is_active       BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS product_specification (
    specification_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id                    BIGINT NOT NULL REFERENCES finished_product(product_id) ON DELETE CASCADE,
    version                       VARCHAR(50) NOT NULL DEFAULT '1.0',
    effective_from                DATE,
    effective_to                  DATE,
    bag_capacity_kg               NUMERIC(18,4),
    bag_width_mm                  NUMERIC(18,4),
    bag_length_mm                 NUMERIC(18,4),
    target_empty_weight_g         NUMERIC(18,4),
    min_empty_weight_g            NUMERIC(18,4),
    max_empty_weight_g            NUMERIC(18,4),
    target_gsm                    NUMERIC(18,4),
    min_gsm                       NUMERIC(18,4),
    max_gsm                       NUMERIC(18,4),
    target_output_bags_per_kg     NUMERIC(18,4),
    min_output_bags_per_kg        NUMERIC(18,4),
    max_output_bags_per_kg        NUMERIC(18,4),
    target_scrap_percentage       NUMERIC(7,3),
    min_scrap_percentage          NUMERIC(7,3),
    max_scrap_percentage          NUMERIC(7,3),
    is_active                     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at                    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_product_spec_version UNIQUE (product_id, version),
    CONSTRAINT chk_product_spec_dates
        CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from),
    CONSTRAINT chk_product_spec_scrap
        CHECK (
            target_scrap_percentage IS NULL OR
            (target_scrap_percentage >= 0 AND target_scrap_percentage <= 100)
        )
);

CREATE TABLE IF NOT EXISTS supplier (
    supplier_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name VARCHAR(150) NOT NULL,
    gst_no        VARCHAR(30) UNIQUE,
    email         VARCHAR(255),
    phone         VARCHAR(30),
    address       TEXT,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS supplier_address (
    supplier_address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id         BIGINT NOT NULL REFERENCES supplier(supplier_id) ON DELETE CASCADE,
    address_type        VARCHAR(30) NOT NULL
        CHECK (address_type IN ('Office','Billing','Warehouse','Other')),
    address_line1       VARCHAR(255) NOT NULL,
    address_line2       VARCHAR(255),
    city                VARCHAR(100),
    state               VARCHAR(100),
    country             VARCHAR(100),
    postal_code         VARCHAR(20),
    is_default          BOOLEAN NOT NULL DEFAULT FALSE,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS supplier_contact (
    supplier_contact_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id         BIGINT NOT NULL REFERENCES supplier(supplier_id) ON DELETE CASCADE,
    contact_name        VARCHAR(150) NOT NULL,
    contact_role        VARCHAR(30)
        CHECK (contact_role IN ('Purchase','Accounts','Sales','Other')),
    email               VARCHAR(255),
    phone               VARCHAR(30),
    is_primary          BOOLEAN NOT NULL DEFAULT FALSE,
    is_active           BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS customer (
    customer_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(150) NOT NULL,
    customer_code VARCHAR(50) NOT NULL UNIQUE,
    email         VARCHAR(255),
    phone         VARCHAR(30),
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS customer_address (
    address_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  BIGINT NOT NULL REFERENCES customer(customer_id) ON DELETE CASCADE,
    address_type VARCHAR(20) NOT NULL CHECK (address_type IN ('Billing','Shipping')),
    address_line1 VARCHAR(255) NOT NULL,
    address_line2 VARCHAR(255),
    city          VARCHAR(100),
    state         VARCHAR(100),
    country       VARCHAR(100),
    postal_code   VARCHAR(20),
    is_default    BOOLEAN NOT NULL DEFAULT FALSE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS vehicle (
    vehicle_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_number VARCHAR(50) NOT NULL UNIQUE,
    vehicle_type   VARCHAR(50),
    capacity       NUMERIC(18,3) CHECK (capacity >= 0),
    capacity_uom_id BIGINT REFERENCES unit_of_measure(uom_id),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS driver (
    driver_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_name    VARCHAR(150) NOT NULL,
    license_number VARCHAR(80) NOT NULL UNIQUE,
    license_expiry DATE,
    phone          VARCHAR(30),
    is_active      BOOLEAN NOT NULL DEFAULT TRUE
);

-- ================================================================
-- 3. USER, SECURITY & APPROVALS
-- ================================================================

CREATE TABLE IF NOT EXISTS app_role (
    role_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(100) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS permission (
    permission_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_name    VARCHAR(100) NOT NULL,
    permission_name VARCHAR(100) NOT NULL,
    CONSTRAINT uq_permission_module_name UNIQUE (module_name, permission_name)
);

CREATE TABLE IF NOT EXISTS role_permission (
    rp_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id       BIGINT NOT NULL REFERENCES app_role(role_id) ON DELETE CASCADE,
    permission_id BIGINT NOT NULL REFERENCES permission(permission_id) ON DELETE CASCADE,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_role_permission UNIQUE (role_id, permission_id)
);

CREATE TABLE IF NOT EXISTS app_user (
    user_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id  BIGINT REFERENCES plant(plant_id),
    user_name VARCHAR(100) NOT NULL UNIQUE,
    email     VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    mfa_secret VARCHAR(255),
    mfa_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_role (
    ur_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES app_role(role_id) ON DELETE CASCADE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_user_role UNIQUE (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS user_mfa (
    mfa_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    mfa_type VARCHAR(20) NOT NULL CHECK (mfa_type IN ('TOTP','SMS','Email')),
    is_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_user_mfa_type UNIQUE (user_id, mfa_type)
);

CREATE TABLE IF NOT EXISTS login_attempt (
    attempt_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT REFERENCES app_user(user_id) ON DELETE SET NULL,
    ip_address    INET,
    is_successful BOOLEAN NOT NULL,
    attempted_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS user_session (
    session_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    session_token TEXT NOT NULL UNIQUE,
    expires_at    TIMESTAMPTZ NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS user_notification_pref (
    pref_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT NOT NULL UNIQUE REFERENCES app_user(user_id) ON DELETE CASCADE,
    email_enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    sms_enabled      BOOLEAN NOT NULL DEFAULT FALSE,
    whatsapp_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    inapp_enabled    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS approval_workflow (
    workflow_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_name VARCHAR(150) NOT NULL,
    entity_type   VARCHAR(100) NOT NULL,
    is_active     BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_approval_workflow UNIQUE (workflow_name, entity_type)
);

CREATE TABLE IF NOT EXISTS approval_request (
    approval_request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workflow_id BIGINT NOT NULL REFERENCES approval_workflow(workflow_id),
    requested_by BIGINT REFERENCES app_user(user_id),
    entity_type VARCHAR(100) NOT NULL,
    entity_id   VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending','Approved','Rejected','Cancelled')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS approval_action (
    approval_action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_request_id BIGINT NOT NULL REFERENCES approval_request(approval_request_id) ON DELETE CASCADE,
    approver_id BIGINT REFERENCES app_user(user_id),
    action VARCHAR(20) NOT NULL CHECK (action IN ('Approve','Reject')),
    comments TEXT,
    acted_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ================================================================
-- 4. PROCUREMENT
-- ================================================================

CREATE TABLE IF NOT EXISTS supplier_material (
    supplier_material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES supplier(supplier_id),
    material_id BIGINT NOT NULL REFERENCES raw_material(material_id),
    purchase_rate NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (purchase_rate >= 0),
    lead_time_days INTEGER NOT NULL DEFAULT 0 CHECK (lead_time_days >= 0),
    minimum_order_qty NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (minimum_order_qty >= 0),
    is_preferred BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_supplier_material UNIQUE (supplier_id, material_id)
);

CREATE TABLE IF NOT EXISTS purchase_order (
    po_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id BIGINT NOT NULL REFERENCES supplier(supplier_id),
    plant_id    BIGINT NOT NULL REFERENCES plant(plant_id),
    po_number   VARCHAR(50) NOT NULL UNIQUE,
    po_date     DATE NOT NULL DEFAULT CURRENT_DATE,
    status      VARCHAR(20) NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft','Approved','Closed','Cancelled')),
    total_amount NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (total_amount >= 0),
    created_by  BIGINT REFERENCES app_user(user_id),
    updated_by  BIGINT REFERENCES app_user(user_id),
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS purchase_order_item (
    po_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id      BIGINT NOT NULL REFERENCES purchase_order(po_id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES raw_material(material_id),
    uom_id     BIGINT NOT NULL REFERENCES unit_of_measure(uom_id),
    quantity   NUMERIC(18,4) NOT NULL CHECK (quantity > 0),
    rate       NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (rate >= 0)
);

CREATE TABLE IF NOT EXISTS goods_receipt (
    gr_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id       BIGINT NOT NULL REFERENCES purchase_order(po_id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouse(warehouse_id),
    gr_number   VARCHAR(50) NOT NULL UNIQUE,
    gr_date     DATE NOT NULL DEFAULT CURRENT_DATE,
    received_by BIGINT REFERENCES app_user(user_id),
    status      VARCHAR(20) NOT NULL DEFAULT 'Open'
        CHECK (status IN ('Open','Closed'))
);

CREATE TABLE IF NOT EXISTS goods_receipt_item (
    gr_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gr_id      BIGINT NOT NULL REFERENCES goods_receipt(gr_id) ON DELETE CASCADE,
    po_item_id BIGINT NOT NULL REFERENCES purchase_order_item(po_item_id),
    material_id BIGINT NOT NULL REFERENCES raw_material(material_id),
    uom_id BIGINT NOT NULL REFERENCES unit_of_measure(uom_id),
    ordered_qty NUMERIC(18,4) NOT NULL CHECK (ordered_qty >= 0),
    received_qty NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (received_qty >= 0),
    pending_qty NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (pending_qty >= 0),
    CONSTRAINT chk_gr_pending CHECK (pending_qty <= ordered_qty)
);

-- ================================================================
-- 5. RAW MATERIAL BATCHES
-- ================================================================

CREATE TABLE IF NOT EXISTS material_batch (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES raw_material(material_id),
    supplier_id BIGINT REFERENCES supplier(supplier_id),
    po_item_id BIGINT REFERENCES purchase_order_item(po_item_id),
    batch_no VARCHAR(80) NOT NULL UNIQUE,
    lot_number VARCHAR(80),
    expiry_date DATE,
    initial_weight_kg NUMERIC(18,4) CHECK (initial_weight_kg IS NULL OR initial_weight_kg >= 0),
    current_weight_kg NUMERIC(18,4) CHECK (current_weight_kg IS NULL OR current_weight_kg >= 0),
    unit_cost NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (unit_cost >= 0),
    received_at TIMESTAMPTZ,
    quality_status VARCHAR(20) NOT NULL DEFAULT 'Available'
        CHECK (quality_status IN ('Available','Hold','Quarantine','Rejected','Expired')),
    status VARCHAR(20) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available','Hold','Quarantine','Rejected','Expired','Consumed','Closed')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_material_batch_lot UNIQUE (lot_number)
);

-- ================================================================
-- 6. PRODUCTION MASTER / COMPOUNDING / FACTORY UNITS
-- ================================================================

CREATE TABLE IF NOT EXISTS bom (
    bom_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES finished_product(product_id),
    version VARCHAR(50) NOT NULL,
    effective_from DATE,
    effective_to DATE,
    yield_quantity NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (yield_quantity >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft','Active','Retired')),
    CONSTRAINT uq_bom_product_version UNIQUE (product_id, version),
    CONSTRAINT chk_bom_dates
        CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from)
);

CREATE TABLE IF NOT EXISTS bom_item (
    bom_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bom_id BIGINT NOT NULL REFERENCES bom(bom_id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES raw_material(material_id),
    uom_id BIGINT NOT NULL REFERENCES unit_of_measure(uom_id),
    quantity NUMERIC(18,4) NOT NULL CHECK (quantity > 0),
    scrap_percentage NUMERIC(7,3) NOT NULL DEFAULT 0
        CHECK (scrap_percentage >= 0 AND scrap_percentage <= 100),
    is_optional BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_bom_material UNIQUE (bom_id, material_id)
);

CREATE TABLE IF NOT EXISTS compounding_bom (
    compounding_bom_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bom_code VARCHAR(50) NOT NULL,
    version VARCHAR(50) NOT NULL,
    effective_from DATE,
    effective_to DATE,
    target_batch_weight_kg NUMERIC(18,4) NOT NULL CHECK (target_batch_weight_kg > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Draft'
        CHECK (status IN ('Draft','Active','Retired')),
    created_by BIGINT REFERENCES app_user(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_compounding_bom_code_version UNIQUE (bom_code, version),
    CONSTRAINT chk_compounding_bom_dates
        CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from)
);

CREATE TABLE IF NOT EXISTS compounding_bom_item (
    compounding_bom_item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compounding_bom_id BIGINT NOT NULL REFERENCES compounding_bom(compounding_bom_id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES raw_material(material_id),
    percentage NUMERIC(7,4) NOT NULL CHECK (percentage >= 0 AND percentage <= 100),
    target_quantity_kg NUMERIC(18,4) NOT NULL CHECK (target_quantity_kg > 0),
    is_required BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_compounding_bom_material UNIQUE (compounding_bom_id, material_id)
);

CREATE TABLE IF NOT EXISTS compounding_batch (
    compounding_batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code VARCHAR(80) NOT NULL UNIQUE,
    compounding_bom_id BIGINT NOT NULL REFERENCES compounding_bom(compounding_bom_id),
    target_weight_kg NUMERIC(18,4) NOT NULL CHECK (target_weight_kg > 0),
    actual_weight_kg NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (actual_weight_kg >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Planned'
        CHECK (status IN ('Planned','InProgress','Completed','Hold','Rejected','Cancelled')),
    created_by BIGINT REFERENCES app_user(user_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS compounding_batch_material (
    compounding_batch_material_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compounding_batch_id BIGINT NOT NULL REFERENCES compounding_batch(compounding_batch_id) ON DELETE CASCADE,
    material_batch_id BIGINT NOT NULL REFERENCES material_batch(batch_id),
    required_qty_kg NUMERIC(18,4) NOT NULL CHECK (required_qty_kg > 0),
    consumed_qty_kg NUMERIC(18,4) NOT NULL DEFAULT 0 CHECK (consumed_qty_kg >= 0),
    CONSTRAINT uq_compounding_batch_material UNIQUE (compounding_batch_id, material_batch_id)
);

CREATE TABLE IF NOT EXISTS production_unit (
    unit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plant(plant_id),
    unit_code VARCHAR(50) NOT NULL,
    unit_name VARCHAR(100) NOT NULL,
    unit_type VARCHAR(30) NOT NULL
        CHECK (unit_type IN ('Extrusion','Weaving','Conversion','Other')),
    sequence_no INTEGER NOT NULL CHECK (sequence_no > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_production_unit_code UNIQUE (unit_code),
    CONSTRAINT uq_production_unit_plant_sequence UNIQUE (plant_id, sequence_no)
);

CREATE TABLE IF NOT EXISTS machine (
    machine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    unit_id BIGINT NOT NULL REFERENCES production_unit(unit_id),
    machine_code VARCHAR(50) NOT NULL UNIQUE,
    machine_name VARCHAR(150) NOT NULL,
    machine_type VARCHAR(100),
    rated_capacity NUMERIC(18,4) CHECK (rated_capacity IS NULL OR rated_capacity >= 0),
    capacity_uom_id BIGINT REFERENCES unit_of_measure(uom_id),
    status VARCHAR(30) NOT NULL DEFAULT 'Available'
        CHECK (status IN ('Available','Running','Maintenance','Stopped','Fault','Retired')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS production_run (
    production_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id BIGINT NOT NULL REFERENCES plant(plant_id),
    bom_id BIGINT NOT NULL REFERENCES bom(bom_id),
    compounding_batch_id BIGINT REFERENCES compounding_batch(compounding_batch_id),
    production_number VARCHAR(50) NOT NULL UNIQUE,
    start_datetime TIMESTAMPTZ,
    end_datetime TIMESTAMPTZ,
