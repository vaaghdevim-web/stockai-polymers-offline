CREATE OR REPLACE FUNCTION validate_double_entry_ledger()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    debit_total NUMERIC(30,8);
    credit_total NUMERIC(30,8);
    entry_count INTEGER;
    target_transaction_id BIGINT;
BEGIN
    target_transaction_id := COALESCE(NEW.ledger_transaction_id, OLD.ledger_transaction_id);

    SELECT
        COUNT(*),
        COALESCE(SUM(quantity) FILTER (WHERE entry_type = 'DEBIT'), 0),
        COALESCE(SUM(quantity) FILTER (WHERE entry_type = 'CREDIT'), 0)
    INTO entry_count, debit_total, credit_total
    FROM inventory_ledger_entry
    WHERE ledger_transaction_id = target_transaction_id;

    IF entry_count < 2 OR debit_total <> credit_total THEN
        RAISE EXCEPTION
            'Inventory ledger transaction % is not balanced: entries=%, debit=%, credit=%',
            target_transaction_id, entry_count, debit_total, credit_total;
    END IF;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validate_double_entry_ledger ON inventory_ledger_entry;
CREATE CONSTRAINT TRIGGER trg_validate_double_entry_ledger
AFTER INSERT OR UPDATE OR DELETE ON inventory_ledger_entry
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_double_entry_ledger();

