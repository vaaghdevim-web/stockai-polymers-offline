CREATE OR REPLACE FUNCTION validate_inventory_update()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.quantity_on_hand < 0 THEN
        RAISE EXCEPTION 'quantity_on_hand cannot be negative';
    END IF;

    IF NEW.reserved_qty < 0 THEN
        RAISE EXCEPTION 'reserved_qty cannot be negative';
    END IF;

    IF NEW.reserved_qty > NEW.quantity_on_hand THEN
        RAISE EXCEPTION
            'reserved_qty (%) cannot exceed quantity_on_hand (%)',
            NEW.reserved_qty, NEW.quantity_on_hand;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_inventory_validate ON inventory;
CREATE TRIGGER trg_inventory_validate
BEFORE INSERT OR UPDATE OF quantity_on_hand, reserved_qty
ON inventory
FOR EACH ROW EXECUTE FUNCTION validate_inventory_update();

